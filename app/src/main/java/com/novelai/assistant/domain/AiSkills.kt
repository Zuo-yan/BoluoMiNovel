        4. 禁用高频生理陈词滥调：严禁反复套用「瞳孔微缩」「嘴角勾起一抹弧度」「后背渗出冷汗」「空气仿佛凝固」「深吸一口气」等模板词，改用贴合当下情境的独特微动作、器物交互或直白简练的情绪陈述。
