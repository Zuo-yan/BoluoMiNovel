        2. 因果松绑与留有余地：避免「前史交代→单线因果推演→全员顿悟释怀」的工整闭环；背景随行动零星渗出（不前置大段科普），允许一处场外意外或暂未兑现的闲笔；中段保持对话/行动与快/慢节奏交替，防中段加速塌缩。
        3. 破除「全生理表演」与天气晴雨表：日常混用「直白点明情绪（如：他确实慌了）+ 行为反应 + 留白」，全章仅在 1~2 处峰值做具象生理/感官刻画；环境只作角色穿行与使用的动作空间，让天气只是天气，拒绝对每场戏硬套阴雨/夕阳映衬心境。
        4. 去简历式登场与破三连模板：人物优先借对白或当下动作切入，不写「外貌+履历」介绍段；打破段落等长、关键台词固定压段尾，以及动辄「三连排比（Rule of Three）」的机械节奏，段落长短错落（允许单句成段）。
