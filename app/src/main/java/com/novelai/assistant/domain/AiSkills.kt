package com.novelai.assistant.domain

/**
 * App 内置 AI 技能：以系统提示词形式注入续写，浓缩自成熟的网文创作方法论。
 */
data class AiSkill(
    val id: String,
    val name: String,
    val description: String,
    /** 作为附加系统提示词注入 */
    val systemPrompt: String
)

/**
 * 续写文风策略：统一融合原著高仿、Sepia 叙事松绑与深度去 AI 味规则，
 * 保持单一高仿模式以贴合原著口吻与人物声纹。
 */
enum class WorkshopStyleMode(
    val id: String,
    val label: String,
    val subtitle: String,
    val promptRules: String
) {
    ORIGINAL_MIMIC(
        id = "original_mimic",
        label = "原著高仿",
        subtitle = "100% 复刻原著口吻与人物声纹 + Sepia 叙事松绑与深度去 AI 味",
        promptRules = """
            【文风模式：原著高仿（融合 Sepia 去 AI 味无缝续写）】
            1. 视角与腔调锁定：严格复刻原著样本的叙事人称（第一人称/第三人称有限视角）、段长分布、标点节奏与用词克制度。
            2. 角色声纹还原：保留原著人物特有的称呼习惯、口头禅、停顿方式与性格底色，遮住名字也能凭对白认出角色。
            3. 克制展示与留白：用具体动作、器物交互与留白推进情绪，日常允许平实直白，不把每处情绪都硬写成生理反应或天气映照；每章围绕核心变故稳步推进，自然留钩收尾。
            4. 严禁跨频串味：原著平实克制则保持冷峻克制，原著诙谐轻快则保持灵动，绝不强行塞入违和的网文套路词或过度雕琢的文青腔。
        """.trimIndent()
    );

    companion object {
        fun fromId(id: String?): WorkshopStyleMode =
            entries.firstOrNull { it.id == id } ?: ORIGINAL_MIMIC
    }
}

/**
 * 续写篇幅档位：控制单次生成的目标字数、节奏密度与最低 maxTokens 保障。
 */
enum class ContinuationLengthMode(
    val id: String,
    val label: String,
    val wordHint: String,
    val minMaxTokens: Int,
    val promptGuidance: String
) {
    SHORT_SCENE(
        id = "short_scene",
        label = "小节推进",
        wordHint = "约 1000-1500 字",
        minMaxTokens = 3072,
        promptGuidance = "【篇幅与节奏控制：小节推进（约 1000-1500 字）】聚焦当前单一场景或一次核心对话交锋，切入迅速、细节凝练，不额外铺开支线，在局势或情绪发生转折处利落收束。"
    ),
    STANDARD_CHAPTER(
        id = "standard_chapter",
        label = "标准单章",
        wordHint = "约 2000-3000 字",
        minMaxTokens = 5120,
        promptGuidance = "【篇幅与节奏控制：标准单章（约 2000-3000 字）】遵循完整的单章「起承转合」结构，围绕一个核心冲突充分展开场景细节、人物对话博弈与情绪递进，章末留下鲜明悬念钩子。"
    ),
    LONG_DEEP(
        id = "long_deep",
        label = "深度长章",
        wordHint = "约 3500-5000 字",
        minMaxTokens = 8192,
        promptGuidance = "【篇幅与节奏控制：深度长章（约 3500-5000 字）】大容量沉浸展开：完整呈现「铺垫蓄势 → 冲突升级 → 核心爆发 → 余波钩子」的多层推进，把环境氛围、器物细节与人物心理博弈写深写透，严禁水字数或空洞概括。"
    );

    companion object {
        fun fromId(id: String?): ContinuationLengthMode =
            entries.firstOrNull { it.id == id } ?: STANDARD_CHAPTER
    }
}

